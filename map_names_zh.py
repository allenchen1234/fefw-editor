NAMES = dict(line.split("|", 1) for line in _NAMES.strip().splitlines())


def name(jp: str) -> str:
    """Translate a Japanese place or an internal network-point identifier."""
    if jp in NAMES:
        return NAMES[jp]
    match = re.fullmatch(r"中スポット(\d+)", jp)
    if match:
        return f"中间点 {int(match[1])}"
    match = re.fullmatch(r"分岐点(\d+)", jp)
    if match:
        return f"岔路点 {int(match[1])}"
    match = re.fullmatch(r"(ダナン海|リル海|砂漠用)分岐(\d+)", jp)
    if match:
        region = {"ダナン海": "达南海", "リル海": "利尔海", "砂漠用": "沙漠"}[match[1]]
        return f"{region}岔路点 {int(match[2])}"
    match = re.fullmatch(r"(ソロモン用砂漠|イベント用)(\d+)", jp)
    if match:
        label = {"ソロモン用砂漠": "所罗门沙漠点", "イベント用": "事件点"}[match[1]]
        return f"{label} {int(match[2])}"
    parts = jp.rsplit("_", 2)
    if len(parts) == 3 and parts[2].isdigit():
        return f"道路：{name(parts[0])} → {name(parts[1])}（{int(parts[2])}）"
    return jp
