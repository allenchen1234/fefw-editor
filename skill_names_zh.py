def _item_words() -> dict[str, str]:
    """Reuse unambiguous item translations for equipment-effect records."""
    data_dir = getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(__file__)))
    try:
        with open(os.path.join(data_dir, "item_ids.json"), encoding="utf8") as fh:
            items = json.load(fh)
    except (OSError, ValueError):
        return {}
    candidates = defaultdict(set)
    for meta in items.values():
        jp = unicodedata.normalize("NFKC", meta.get("jp") or "").strip()
        jp = re.sub(r"\+\d+$", "", jp)
        zh = item_names_zh.chinese_name(meta.get("en") or "", meta)
        if zh:
            zh = re.sub(r"\s*\+\s*\d+$", "", zh)
            if len(jp) >= 2 and not any(ch in jp for ch in "_[]()"):
                candidates[jp].add(zh)
    return {jp: next(iter(values)) for jp, values in candidates.items() if len(values) == 1}


