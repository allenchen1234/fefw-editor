_INTERNAL_WORDS.update({unicodedata.normalize("NFKC", jp): zh
                        for jp, zh in unit_names_zh.ALL_NAMES.items()})
_INTERNAL_WORDS.update(NAMES)
_TOKEN = re.compile("|".join(re.escape(k) for k in sorted(_INTERNAL_WORDS, key=len, reverse=True)))


def _internal_name(jp: str) -> str | None:
    """Translate structured internal labels without guessing unknown words."""
    original = jp
    prefix = ""
    if jp.startswith("[e]"):
        prefix, jp = "内部效果·", jp[3:]
    out = []
    recognised_cjk = False
    at = 0
    while at < len(jp):
        match = _TOKEN.match(jp, at)
        if match:
            recognised_cjk |= any(ord(ch) > 127 for ch in match.group())
            out.append(_INTERNAL_WORDS[match.group()])
            at = match.end()
        elif jp[at].isascii() or jp[at] in "・、・()[]+-×":
            out.append(jp[at])
            at += 1
        else:
            return None
    result = prefix + "".join(out)
    # Do not treat unchanged identifiers or plain Latin text as translations.
    return result if result and (result != original or recognised_cjk) else None


def chinese_name(meta: dict | None) -> str | None:
    """Return a translation for a known Japanese SID and recognised variants."""
    if not meta:
        return None
    if meta.get("zh_CN"):
        return meta["zh_CN"]
    jp = unicodedata.normalize("NFKC", meta.get("jp") or "").strip()
    if jp in NAMES:
        return NAMES[jp]
    hp = re.fullmatch(r"HP\+(\d+)", jp)
    if hp:
        return "HP+" + hp.group(1)
    # Only derive variants from an exact known base and a recognised suffix.
    # Distinct forms remain labelled and retain their original ID in the picker.
    match = re.fullmatch(r"(.+?)(\+{0,2})(?:\(([^()]+)\))?(\+{0,2})", jp)
    if match:
        base, before, tag, after = match.groups()
        if base in NAMES and (not tag or tag in VARIANT_TAGS):
            return (NAMES[base] + before + (f"（{VARIANT_TAGS[tag]}）" if tag else "") + after)
    return _internal_name(jp)


def display_name(meta: dict | None, fallback: str, chinese: bool) -> str:
    return (chinese_name(meta) or fallback) if chinese else fallback
