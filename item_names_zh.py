def chinese_name(english: str, meta: dict | None = None) -> str | None:
    """Return a known Chinese name, including its forge level, or None."""
    meta = meta or {}
    if meta.get("zh_CN"):
        return meta["zh_CN"]
    jp = unicodedata.normalize("NFKC", meta.get("jp") or "").strip()
    jp_base = re.sub(r"_(?:SC[0-9X]+_[0-9]+|第3部)$", "", jp)
    forge = re.search(r"\+(\d+)$", jp_base)
    if forge:
        jp_base = jp_base[:forge.start()]
    if jp_base in JP_NAMES:
        return JP_NAMES[jp_base] + (f" +{forge.group(1)}" if forge else "")
    currency = re.fullmatch(r"(\d+)g", english, re.IGNORECASE)
    if currency:
        return f"{currency.group(1)} 金币"
    prototype = re.fullmatch(r"Prototype (I|V|VII|XI)(?::\s*(\|+))?", english)
    if prototype:
        number = {"I": 1, "V": 5, "VII": 7, "XI": 11}[prototype.group(1)]
        return f"试作品 {number} 号" + (f"（变体 {len(prototype.group(2))}）" if prototype.group(2) else "")
    jp = re.sub(r"_SC\d+_\d+$", "", meta.get("jp") or "")
    parts = [part for part in jp.split("_") if part]
    if len(parts) > 1 and parts[0] in MONSTERS and all(p in MONSTER_PARTS for p in parts[1:]):
        return " · ".join([MONSTERS[parts[0]]] + [MONSTER_PARTS[p] for p in parts[1:]])
    match = re.match(r"^(.*?)(\s*\+\s*\d+)?$", english)
    if not match:
        return None
    base, suffix = match.groups()
    translated = NAMES.get(base)
    return translated + (suffix or "") if translated else None


def display_name(english: str, meta: dict | None, chinese: bool) -> str:
    return (chinese_name(english, meta) or english) if chinese else english
